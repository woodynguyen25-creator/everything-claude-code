"""/build-skill — meta-agent that generates new Hermes skills.

Pattern from AI Masterclass video #25 (LLM generates n8n workflow JSON from
NL prompt). Adapted: LLM generates skill.yaml + main.py from a description,
using `voice-note` as the canonical source-of-truth template (one good
example > a vector DB of everything — also from #25).

Usage:
  /build-skill <skill-name>: <one-sentence description>

Example:
  /build-skill weather-brief: pulls morning weather for Houston and saves to inbox

Output:
  AIOS/Reports/build-skill-{name}/skill.yaml
  AIOS/Reports/build-skill-{name}/main.py
  AIOS/Reports/build-skill-{name}/README.md  (deploy instructions)

Read-only. Never auto-installs. Woody reviews then scp's manually.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path
from typing import Any, Dict, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
try:
    from _shared import models as workers  # type: ignore
    from _shared import vault              # type: ignore
except ImportError:
    workers = None
    vault = None

# Source-of-truth template lives in voice-note. Nate's lesson from video #25:
# one good example beats vectorizing the whole codebase.
HERMES_HOME = Path(os.environ.get("HERMES_HOME", "/home/hermes/.hermes"))
TEMPLATE_SKILL = HERMES_HOME / "skills" / "voice-note"


BUILD_SYSTEM_PROMPT = """\
You generate Hermes Agent skills for Woody Nguyen's AIOS.

You will be given:
1. A template skill (skill.yaml + main.py) — this is the source of truth for
   the shape every Hermes skill follows
2. A natural-language description of the new skill
3. The skill name

Generate TWO files:
- A new skill.yaml that follows the template's exact shape (frontmatter keys,
  YAML indentation, trigger format)
- A new main.py that:
  - Imports `vault` and (if needed) `models` from `_shared`
  - Has an entry-point function matching skill.yaml's `entrypoint`
  - Logs every successful run via `vault.log_activity()`
  - Handles vault unavailability gracefully (vault is None)
  - Returns {"reply": str, ...other-fields} from the entry point

Rules:
- Follow the template's exact import + sys.path pattern
- Keep main.py under 250 lines
- Type-hint function signatures
- No emojis in code; emojis only in user-facing reply strings
- Match the template's docstring style (top-of-file describes pipeline)
- Use Claude Max for synthesis tasks, Cerebras/Groq for fast scans, free
  tiers preferred unless a metered worker is genuinely needed

Return ONLY this exact format with two fenced code blocks — no other text:

```yaml
<contents of new skill.yaml>
```

```python
<contents of new main.py>
```
"""


def parse_args(text: str) -> Tuple[str, str]:
    """Parse `<name>: <description>` from the Telegram args."""
    if ":" not in text:
        return "", text.strip()
    name_part, desc_part = text.split(":", 1)
    name = re.sub(r"[^a-z0-9-]", "", name_part.strip().lower())
    return name, desc_part.strip()


def load_template() -> Dict[str, str]:
    """Read the template skill files into a single payload."""
    yaml_path = TEMPLATE_SKILL / "skill.yaml"
    main_path = TEMPLATE_SKILL / "main.py"
    if not yaml_path.exists() or not main_path.exists():
        return {"yaml": "", "main": "", "error": f"template not found at {TEMPLATE_SKILL}"}
    return {
        "yaml": yaml_path.read_text(),
        "main": main_path.read_text(),
        "error": "",
    }


def build_prompt(name: str, description: str, template: Dict[str, str]) -> str:
    return (
        f"Skill name: `{name}`\n"
        f"Description: {description}\n\n"
        f"--- TEMPLATE skill.yaml ---\n```yaml\n{template['yaml']}\n```\n\n"
        f"--- TEMPLATE main.py ---\n```python\n{template['main']}\n```\n\n"
        "Generate the new skill files now."
    )


def parse_response(text: str) -> Tuple[str, str, str]:
    """Extract yaml + python fenced blocks. Returns (yaml, py, error)."""
    yaml_match = re.search(r"```yaml\s*\n(.+?)\n```", text, re.DOTALL)
    python_match = re.search(r"```python\s*\n(.+?)\n```", text, re.DOTALL)
    if not yaml_match or not python_match:
        return "", "", "missing yaml or python fenced block in LLM response"
    return yaml_match.group(1).strip(), python_match.group(1).strip(), ""


def render_readme(name: str, description: str) -> str:
    return f"""# {name} — Hermes skill (proposed)

> Generated by `/build-skill`. Review before deploying.

## What it does

{description}

## Deploy

```powershell
scp -r dashboard\\hetzner\\skills\\{name} root@142.93.12.177:/home/hermes/.hermes/skills/
ssh root@142.93.12.177 'sudo -u hermes -i'
hermes skill install ~/.hermes/skills/{name}
hermes gateway restart
```

## Smoke test

Run the generated tests (if any) before deploying:

```bash
cd ~/.hermes/skills/{name}
python -m pytest -q
```

## Notes

- This file lives in `AIOS/Reports/` only until you copy it into
  `dashboard/hetzner/skills/{name}/`. Treat as a proposal.
- The LLM may have invented imports or capabilities. Review main.py before
  installing.
"""


def run(event: Dict[str, Any]) -> Dict[str, Any]:
    text = (event.get("text") or "").strip()
    name, description = parse_args(text)
    if not name or not description:
        return {
            "reply": (
                "Usage: `/build-skill <name>: <description>`\n\n"
                "Example: `/build-skill weather-brief: pulls Houston weather, saves to inbox`"
            )
        }
    if workers is None or vault is None:
        return {"reply": "⚠️ shared workers/vault unavailable; can't reach Claude Max"}

    template = load_template()
    if template.get("error"):
        return {"reply": f"⚠️ {template['error']}"}

    prompt = build_prompt(name, description, template)
    try:
        result = workers.dispatch(
            "claude-max",
            prompt,
            system=BUILD_SYSTEM_PROMPT,
            max_tokens=6_000,
            allow_fallback=False,  # this needs Claude's structural taste
        )
    except workers.WorkerError as exc:  # type: ignore[attr-defined]
        return {"reply": f"⚠️ Claude Max unreachable: {exc}"}

    yaml_text, py_text, parse_err = parse_response(result["text"])
    if parse_err:
        return {"reply": f"⚠️ Couldn't parse LLM response: {parse_err}"}

    folder = f"AIOS/Reports/build-skill-{name}"
    try:
        vault.write(folder, "skill.yaml", yaml_text, mode="overwrite")
        vault.write(folder, "main.py", py_text, mode="overwrite")
        vault.write(folder, "README.md", render_readme(name, description), mode="overwrite")
        vault.log_activity(
            task="build-skill",
            outcome="✅",
            summary=f"generated {name}",
            tokens=result["tokens_in"] + result["tokens_out"],
            cost_usd=result["cost_usd"],
            notes=f"saved to {folder}",
        )
    except Exception as exc:
        return {"reply": f"⚠️ generated but couldn't save: {exc}"}

    return {
        "reply": (
            f"🛠️ *Built skill `{name}`*\n\n"
            f"Files saved to `{folder}`:\n"
            f"- `skill.yaml` ({len(yaml_text):,} chars)\n"
            f"- `main.py` ({len(py_text):,} chars)\n"
            f"- `README.md` (deploy instructions)\n\n"
            f"Review then deploy with the steps in README.md."
        ),
        "saved_folder": folder,
        "name": name,
    }
