#!/usr/bin/env bash
#
# smoke-test.sh — verify Hermes v2 end-to-end after a fresh deploy.
#
# Run this from the Droplet as the `hermes` user:
#   sudo -u hermes -i
#   bash ~/.hermes/scripts/smoke-test.sh
#
# Each check prints PASS/FAIL/SKIP and exits non-zero on any FAIL.

set -u

PASS=0
FAIL=0
SKIP=0

ECC_BRIDGE_URL="${ECC_BRIDGE_URL:-http://100.69.115.98:3738}"
ECC_BRIDGE_TOKEN="${ECC_BRIDGE_TOKEN:-}"

check() {
  local label="$1"
  local result="$2"  # PASS | FAIL | SKIP
  local detail="${3:-}"
  case "$result" in
    PASS) PASS=$((PASS+1)); printf "  \e[32m✓ PASS\e[0m  %-40s %s\n" "$label" "$detail" ;;
    FAIL) FAIL=$((FAIL+1)); printf "  \e[31m✗ FAIL\e[0m  %-40s %s\n" "$label" "$detail" ;;
    SKIP) SKIP=$((SKIP+1)); printf "  \e[33m~ SKIP\e[0m  %-40s %s\n" "$label" "$detail" ;;
  esac
}

section() {
  printf "\n\e[1m== %s ==\e[0m\n" "$1"
}

# ──────────────────────────────────────────────────────────────────────────
section "Environment"
# ──────────────────────────────────────────────────────────────────────────

if [ -n "${ECC_BRIDGE_TOKEN}" ]; then
  check "ECC_BRIDGE_TOKEN set" PASS
else
  check "ECC_BRIDGE_TOKEN set" FAIL "export it before running"
fi

if [ -n "${GROQ_API_KEY:-}" ]; then
  check "GROQ_API_KEY set" PASS
else
  check "GROQ_API_KEY set" FAIL "voice-note skill will fail without this"
fi

if [ -n "${TELEGRAM_BOT_TOKEN:-}" ]; then
  check "TELEGRAM_BOT_TOKEN set" PASS
else
  check "TELEGRAM_BOT_TOKEN set" SKIP "Hermes manages this internally"
fi

# ──────────────────────────────────────────────────────────────────────────
section "Hermes runtime"
# ──────────────────────────────────────────────────────────────────────────

if command -v hermes >/dev/null 2>&1; then
  check "hermes binary on PATH" PASS "$(hermes --version 2>/dev/null | head -1)"
else
  check "hermes binary on PATH" FAIL
fi

if hermes gateway status 2>/dev/null | grep -qi 'running\|active\|ok'; then
  check "hermes gateway running" PASS
else
  check "hermes gateway running" FAIL "try: systemctl --user status hermes-gateway"
fi

# ──────────────────────────────────────────────────────────────────────────
section "Installed skills"
# ──────────────────────────────────────────────────────────────────────────

for skill in voice-note triad-router aios-audit aios-onboard aios-status; do
  if hermes skill list 2>/dev/null | grep -q "${skill}"; then
    check "skill installed: ${skill}" PASS
  else
    check "skill installed: ${skill}" FAIL "hermes skill install ~/.hermes/skills/${skill}"
  fi
done

# ──────────────────────────────────────────────────────────────────────────
section "PC bridge reachability"
# ──────────────────────────────────────────────────────────────────────────

if curl -sS -m 5 -o /dev/null -w "%{http_code}" "${ECC_BRIDGE_URL}/api/vault/write" | grep -q '^200$'; then
  check "GET /api/vault/write" PASS
else
  check "GET /api/vault/write" FAIL "PC dashboard down or Tailscale broken"
fi

if [ -n "${ECC_BRIDGE_TOKEN}" ]; then
  code=$(curl -sS -m 5 -o /dev/null -w "%{http_code}" \
    -H "Authorization: Bearer ${ECC_BRIDGE_TOKEN}" \
    "${ECC_BRIDGE_URL}/api/vault/list?folder=AIOS&limit=5")
  if [ "${code}" = "200" ]; then
    check "GET /api/vault/list (authed)" PASS
  else
    check "GET /api/vault/list (authed)" FAIL "HTTP ${code} — token mismatch?"
  fi
fi

# ──────────────────────────────────────────────────────────────────────────
section "Vault write round-trip"
# ──────────────────────────────────────────────────────────────────────────

if [ -n "${ECC_BRIDGE_TOKEN}" ]; then
  ts=$(date -u +%Y%m%dT%H%M%SZ)
  test_filename="smoke-test-${ts}.md"
  body=$(cat <<EOF
{
  "folder": "_inbox",
  "filename": "${test_filename}",
  "content": "# Smoke test ${ts}\n\nGenerated by smoke-test.sh",
  "mode": "create"
}
EOF
  )
  write_code=$(curl -sS -m 10 -o /tmp/smoke-write.json -w "%{http_code}" \
    -X POST -H "Content-Type: application/json" \
    -H "Authorization: Bearer ${ECC_BRIDGE_TOKEN}" \
    -d "${body}" "${ECC_BRIDGE_URL}/api/vault/write")

  if [ "${write_code}" = "200" ] && grep -q '"success":true' /tmp/smoke-write.json; then
    check "POST /api/vault/write" PASS "wrote ${test_filename}"

    # Read it back
    read_code=$(curl -sS -m 10 -o /tmp/smoke-read.json -w "%{http_code}" \
      -H "Authorization: Bearer ${ECC_BRIDGE_TOKEN}" \
      "${ECC_BRIDGE_URL}/api/vault/read?folder=_inbox&filename=${test_filename}")
    if [ "${read_code}" = "200" ] && grep -q 'Smoke test' /tmp/smoke-read.json; then
      check "GET /api/vault/read round-trip" PASS
    else
      check "GET /api/vault/read round-trip" FAIL "HTTP ${read_code}"
    fi
  else
    check "POST /api/vault/write" FAIL "HTTP ${write_code}: $(head -c 200 /tmp/smoke-write.json)"
  fi
fi

# ──────────────────────────────────────────────────────────────────────────
section "State directory"
# ──────────────────────────────────────────────────────────────────────────

STATE_DIR="${HOME}/.hermes/state"
if [ -d "${STATE_DIR}" ]; then
  check "~/.hermes/state exists" PASS
else
  check "~/.hermes/state exists" FAIL "mkdir -p ${STATE_DIR}"
fi

# ──────────────────────────────────────────────────────────────────────────
section "Cron jobs visible"
# ──────────────────────────────────────────────────────────────────────────

if hermes cron list 2>/dev/null | grep -q 'aios-audit-weekly'; then
  check "cron: aios-audit-weekly" PASS
else
  check "cron: aios-audit-weekly" FAIL "hermes cron reload"
fi
if hermes cron list 2>/dev/null | grep -q 'voice-flush'; then
  check "cron: voice-flush" PASS
else
  check "cron: voice-flush" FAIL "hermes cron reload"
fi
if hermes cron list 2>/dev/null | grep -q 'deepseek-spend-reset'; then
  check "cron: deepseek-spend-reset" PASS
else
  check "cron: deepseek-spend-reset" FAIL "hermes cron reload"
fi

# ──────────────────────────────────────────────────────────────────────────
section "Skill unit tests"
# ──────────────────────────────────────────────────────────────────────────

for skill in voice-note triad-router; do
  if [ -f "${HOME}/.hermes/skills/${skill}/test_$(echo "${skill}" | tr - _).py" ]; then
    if (cd "${HOME}/.hermes/skills/${skill}" && python -m pytest -q 2>/dev/null); then
      check "pytest: ${skill}" PASS
    else
      check "pytest: ${skill}" FAIL "investigate test output"
    fi
  else
    check "pytest: ${skill}" SKIP "no test file"
  fi
done

# ──────────────────────────────────────────────────────────────────────────
section "Summary"
# ──────────────────────────────────────────────────────────────────────────

printf "\n  \e[32mPASS: %d\e[0m  \e[31mFAIL: %d\e[0m  \e[33mSKIP: %d\e[0m\n\n" "${PASS}" "${FAIL}" "${SKIP}"

if [ "${FAIL}" -gt 0 ]; then
  exit 1
fi
exit 0
