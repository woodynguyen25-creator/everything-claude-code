#!/usr/bin/env node
/**
 * activity-log-rollup.js
 *
 * 1st of each month at 10:00 CT.
 * Reads AIOS-ACTIVITY-LOG.md from the vault, computes monthly summary:
 *   - task → run count
 *   - task → success rate
 *   - tasks idle 30+ days
 *   - total metered cost
 *   - failure-prone candidates (>20% failure rate)
 * Writes a dated report to Command Center/AIOS/Reports/.
 * Pings Telegram with the headline.
 *
 * Per AI Masterclass adoption #6.
 */

const http = require('node:http');
const { execSync } = require('node:child_process');

const BRIDGE_URL = process.env.ECC_BRIDGE_URL || 'http://100.69.115.98:3738';
const BRIDGE_TOKEN = process.env.ECC_BRIDGE_TOKEN || '';
const TELEGRAM_TOKEN = process.env.TELEGRAM_BOT_TOKEN || '';
const TELEGRAM_CHAT = process.env.TELEGRAM_ALLOWED_USERS || '';

const ACTIVITY_FOLDER = 'AIOS';
const ACTIVITY_FILE = 'AIOS-ACTIVITY-LOG.md';
const REPORT_FOLDER = 'AIOS/Reports';

function request(method, urlStr, body) {
  return new Promise((resolve, reject) => {
    const u = new URL(urlStr);
    const headers = {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${BRIDGE_TOKEN}`,
    };
    const data = body ? JSON.stringify(body) : null;
    if (data) headers['Content-Length'] = Buffer.byteLength(data);
    const req = http.request(
      { hostname: u.hostname, port: u.port, path: u.pathname + u.search, method, headers },
      (res) => {
        let chunks = '';
        res.on('data', (c) => (chunks += c));
        res.on('end', () => {
          try {
            const parsed = JSON.parse(chunks);
            if (res.statusCode >= 200 && res.statusCode < 300) resolve(parsed);
            else reject(new Error(`HTTP ${res.statusCode}: ${chunks.slice(0, 200)}`));
          } catch {
            reject(new Error(`bad JSON: ${chunks.slice(0, 200)}`));
          }
        });
      }
    );
    req.on('error', reject);
    if (data) req.write(data);
    req.end();
  });
}

function parseRows(markdown) {
  // Activity log uses pipe-table format. Skip header rows.
  const lines = markdown.split('\n').filter((l) => l.startsWith('|'));
  if (lines.length < 3) return [];
  const dataLines = lines.slice(2); // skip header + separator
  return dataLines
    .map((l) => l.split('|').map((c) => c.trim()))
    .filter((cols) => cols.length >= 8)
    .map((cols) => ({
      timestamp: cols[1],
      task: cols[2],
      outcome: cols[3],
      summary: cols[4],
      tokens: cols[5] ? Number(cols[5]) || 0 : 0,
      cost: cols[6] ? Number(cols[6]) || 0 : 0,
      notes: cols[7],
    }))
    .filter((r) => r.timestamp && r.task);
}

function withinLastMonth(rows, monthKey) {
  return rows.filter((r) => r.timestamp.startsWith(monthKey));
}

function rollup(rows) {
  const byTask = new Map();
  for (const r of rows) {
    if (!byTask.has(r.task)) {
      byTask.set(r.task, {
        task: r.task,
        runs: 0,
        successes: 0,
        failures: 0,
        partials: 0,
        retries: 0,
        tokens: 0,
        cost: 0,
        lastSeen: r.timestamp,
      });
    }
    const agg = byTask.get(r.task);
    agg.runs++;
    agg.tokens += r.tokens;
    agg.cost += r.cost;
    if (r.timestamp > agg.lastSeen) agg.lastSeen = r.timestamp;
    if (r.outcome.includes('✅')) agg.successes++;
    else if (r.outcome.includes('⚠️')) agg.partials++;
    else if (r.outcome.includes('❌')) agg.failures++;
    else if (r.outcome.includes('🔁')) agg.retries++;
  }
  return Array.from(byTask.values()).map((agg) => ({
    ...agg,
    successRate: agg.runs ? agg.successes / agg.runs : 0,
    failureRate: agg.runs ? agg.failures / agg.runs : 0,
  }));
}

function buildReport(monthKey, monthRows, allRows) {
  const aggs = rollup(monthRows).sort((a, b) => b.runs - a.runs);
  const totalRuns = monthRows.length;
  const totalCost = monthRows.reduce((s, r) => s + r.cost, 0);
  const totalTokens = monthRows.reduce((s, r) => s + r.tokens, 0);

  const allTaskNames = new Set(allRows.map((r) => r.task));
  const monthTaskNames = new Set(monthRows.map((r) => r.task));
  const cutoff = new Date(Date.now() - 30 * 24 * 60 * 60 * 1000).toISOString();
  const idleTasks = Array.from(allTaskNames).filter((name) => {
    const lastSeen = allRows
      .filter((r) => r.task === name)
      .map((r) => r.timestamp)
      .sort()
      .pop();
    return lastSeen && lastSeen < cutoff && !monthTaskNames.has(name);
  });

  const failureProne = aggs.filter((a) => a.runs >= 5 && a.failureRate > 0.2);

  let body = `---\n`;
  body += `title: Activity Log Rollup ${monthKey}\n`;
  body += `tags: [report, rollup, automation, telemetry]\n`;
  body += `created: ${new Date().toISOString().slice(0, 10)}\n`;
  body += `---\n\n`;
  body += `# 📊 Activity Rollup — ${monthKey}\n\n`;
  body += `> Auto-generated by \`activity-log-rollup.js\`.\n\n`;
  body += `## Headline\n\n`;
  body += `- **Total runs**: ${totalRuns}\n`;
  body += `- **Unique tasks**: ${aggs.length}\n`;
  body += `- **Total tokens**: ${totalTokens.toLocaleString()}\n`;
  body += `- **Total metered cost**: $${totalCost.toFixed(4)}\n`;
  body += `- **Idle 30+ days**: ${idleTasks.length}\n`;
  body += `- **Failure-prone (>20% fail rate, ≥5 runs)**: ${failureProne.length}\n\n`;

  body += `## Per-task summary\n\n`;
  body += `| Task | Runs | Success | Failure | Tokens | Cost USD | Last seen |\n`;
  body += `|---|---|---|---|---|---|---|\n`;
  for (const a of aggs) {
    body += `| ${a.task} | ${a.runs} | ${(a.successRate * 100).toFixed(0)}% | ${(a.failureRate * 100).toFixed(0)}% | ${a.tokens.toLocaleString()} | $${a.cost.toFixed(4)} | ${a.lastSeen.slice(0, 16)} |\n`;
  }
  body += `\n`;

  if (failureProne.length) {
    body += `## ⚠️ Failure-prone tasks\n\n`;
    for (const a of failureProne) {
      body += `- **${a.task}** — ${(a.failureRate * 100).toFixed(0)}% fail rate over ${a.runs} runs. Investigate or kill.\n`;
    }
    body += `\n`;
  }

  if (idleTasks.length) {
    body += `## 🌙 Idle 30+ days\n\n`;
    for (const t of idleTasks) {
      body += `- ${t}\n`;
    }
    body += `\n`;
  }

  body += `## Recommended actions\n\n`;
  body += `- [ ] Review failure-prone tasks (fix root cause or kill)\n`;
  body += `- [ ] Decide on idle tasks (revive or delete)\n`;
  body += `- [ ] If total cost > $10, audit which DeepSeek calls were wasteful\n`;
  body += `- [ ] If a task is 100% green, promote it to a hard-coded rule in CLAUDE.md\n`;

  return { body, headline: `${totalRuns} runs · ${aggs.length} tasks · $${totalCost.toFixed(2)} spent · ${failureProne.length} failure-prone` };
}

function notifyTelegram(text) {
  if (!TELEGRAM_TOKEN || !TELEGRAM_CHAT) return;
  try {
    const url = `https://api.telegram.org/bot${TELEGRAM_TOKEN}/sendMessage`;
    const body = JSON.stringify({
      chat_id: TELEGRAM_CHAT.split(',')[0],
      text,
      parse_mode: 'Markdown',
    });
    execSync(
      `curl -sS -X POST -H 'Content-Type: application/json' -d '${body.replace(/'/g, "'\\''")}' ${url}`,
      { stdio: 'ignore', timeout: 10_000 }
    );
  } catch {
    // best effort
  }
}

async function main() {
  if (!BRIDGE_TOKEN) {
    console.error('[activity-log-rollup] ECC_BRIDGE_TOKEN not set, aborting');
    process.exit(1);
  }

  const readUrl = `${BRIDGE_URL}/api/vault/read?folder=${encodeURIComponent(ACTIVITY_FOLDER)}&filename=${encodeURIComponent(ACTIVITY_FILE)}`;
  const readResult = await request('GET', readUrl);
  if (!readResult.success) {
    throw new Error(`activity log read failed: ${readResult.error}`);
  }

  const rows = parseRows(readResult.data.content);

  // Rollup last completed month
  const now = new Date();
  const lastMonth = new Date(now.getFullYear(), now.getMonth() - 1, 1);
  const monthKey = lastMonth.toISOString().slice(0, 7);
  const monthRows = withinLastMonth(rows, monthKey);

  if (monthRows.length === 0) {
    console.log(`[activity-log-rollup] no rows for ${monthKey}, skipping`);
    process.exit(0);
  }

  const { body, headline } = buildReport(monthKey, monthRows, rows);
  const filename = `activity-log-rollup-${monthKey}.md`;

  const writeResult = await request('POST', `${BRIDGE_URL}/api/vault/write`, {
    folder: REPORT_FOLDER,
    filename,
    content: body,
    mode: 'overwrite',
  });
  if (!writeResult.success) {
    throw new Error(`report write failed: ${writeResult.error}`);
  }

  console.log(`[activity-log-rollup] saved ${REPORT_FOLDER}/${filename}`);
  notifyTelegram(`📊 *Activity Rollup — ${monthKey}*\n\n${headline}\n\nReport: \`${REPORT_FOLDER}/${filename}\``);
}

main().catch((err) => {
  console.error(`[activity-log-rollup] fatal: ${err.message}`);
  process.exit(1);
});
