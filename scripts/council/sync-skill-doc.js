#!/usr/bin/env node
/**
 * Regenerate the ROSTER block inside the council skill doc from roster.js.
 *
 * WHY THIS EXISTS
 * On 2026-08-23 a session was told the council could now read images and said no,
 * it cannot — correctly, from what it had read. The skill doc it loads
 * (~/.claude/skills/council/SKILL.md) still described an early-August roster:
 * "Grok-4.5 lead", cerebras alive, groq on a decommissioned llama id, no gemini
 * seat, no haiku seat, and none of --private/--research/--decide/--image.
 *
 * That is the third time a hand-maintained copy of seat placement has rotted, and
 * roster.js opens by calling itself "the SINGLE SOURCE OF TRUTH for seat
 * placement". The lesson is not "update the doc" — that has been done twice and
 * bought about three weeks each time. It is that a PROSE COPY OF A VOLATILE FACT
 * IS A BUG, and the fix is to stop hand-writing it: the doc keeps the doctrine
 * (when to convene, how to write a packet) and GENERATES the parts that change.
 *
 * `--check` makes the drift a test failure instead of a discovery six weeks later.
 *
 * Usage:
 *   node scripts/council/sync-skill-doc.js          # rewrite the block in place
 *   node scripts/council/sync-skill-doc.js --check  # exit 1 if the doc is stale
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const {
  SEATS, LEAD_SEATS, WORKER_SEATS, BENCHED_SEATS,
  VISION_SEATS, SEARCH_SEATS, TRAINS_ON_INPUT_SEATS,
} = require('./roster');

const BEGIN = '<!-- BEGIN GENERATED ROSTER — edit roster.js, not this block -->';
const END = '<!-- END GENERATED ROSTER -->';

/**
 * The doc a session actually loads lives in the USER skills directory, not in this
 * repo — and it deliberately stays there.
 *
 * A tracked copy under skills/ was written first and removed the same hour: this
 * repository is PUBLIC, and that doc carries absolute machine paths, monthly spend
 * figures, the Google plan's data-use terms, and Woody by name. Committing it is the
 * same class of mistake as the 2026-08-21 upstream leak. It also forced the README
 * skill counts in eight files across three languages to churn for a document that is
 * not an ECC skill at all.
 *
 * Consequence, accepted knowingly: this file is the only copy and is not in git. If
 * it should be versioned, it belongs in a PRIVATE repo, not this one.
 */
const HOME = process.env.USERPROFILE || process.env.HOME || '';
const TARGETS = [
  path.join(HOME, '.claude', 'skills', 'council', 'SKILL.md'),
];

/**
 * Codex (Sol) loads its OWN copy of every skill from ~/.codex/skills — the ECC
 * compat sync copies Claude skills across ONCE and never overwrites
 * (codex-compat/manifest.json: overwriteExistingCodexSkills=false). Measured
 * 2026-08-24: the Codex council doc was frozen at 2026-07-16 — no --image, no
 * --research, the OLD privacy default — while the Claude doc had been regenerated
 * three times. Same bug as the one this file exists for, one directory over.
 *
 * So the Codex copy is not a second target with its own markers: it is a byte
 * MIRROR of the Claude doc, written by this script and checked by the test suite.
 * Absent ~/.codex → nothing to mirror (CI, other machines) and that is not a failure.
 */
const MIRRORS = [
  { from: TARGETS[0], to: path.join(HOME, '.codex', 'skills', 'council', 'SKILL.md') },
];

function mirrorStatus(from, to) {
  if (!fs.existsSync(from)) return { from, to, status: 'absent' };
  if (!fs.existsSync(path.dirname(path.dirname(to)))) return { from, to, status: 'absent' }; // no ~/.codex/skills
  const src = fs.readFileSync(from, 'utf8');
  if (fs.existsSync(to) && fs.readFileSync(to, 'utf8') === src) return { from, to, status: 'current' };
  return { from, to, status: 'stale', next: src };
}

const seat = id => SEATS.find(s => s.id === id);

function visionCell(s) {
  if (!s.vision) return 'no';
  return { native: 'yes (native)', 'read-tool': 'yes (reads the file)', 'gemini-api': 'yes (Gemini API)' }[s.vision] || `yes (${s.vision})`;
}

function reachCell(s) {
  const bits = [];
  if (s.toolAccess && s.toolAccess !== 'api') bits.push(s.toolAccess);
  if (s.liveSearch) bits.push('live web + X');
  return bits.length ? bits.join(' · ') : 'prompt-bound';
}

function table(ids, heading) {
  const rows = ids.map(id => {
    const s = seat(id);
    if (!s) return null;
    const priv = s.dataTerms === 'TRAINS-ON-INPUT' ? '⚠ trains on input' : s.dataTerms;
    return `| \`${s.id}\` | ${s.model} | ${reachCell(s)} | ${visionCell(s)} | ${priv} |`;
  }).filter(Boolean);
  return [
    `**${heading}**`,
    '',
    '| seat | model | can reach | sees images | data terms |',
    '|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

function buildBlock() {
  const blind = SEATS.filter(s => !s.vision).map(s => s.id);
  return [
    BEGIN,
    '',
    '<!-- Generated by scripts/council/sync-skill-doc.js from roster.js. Do not hand-edit: -->',
    '<!-- tests/council/skill-doc.test.js fails the suite when this block drifts. -->',
    '',
    table(LEAD_SEATS, 'LEAD — these vote. One seat per lab, because same-lab models fail the same way.'),
    '',
    table(WORKER_SEATS, 'WORKER (`--workers`) — execute an already-decided spec. They do not vote.'),
    '',
    table(BENCHED_SEATS, 'BENCHED — callable with `--to`, excluded from default rosters.'),
    '',
    '**Capabilities, as declared by the roster (not by assumption):**',
    '',
    `- **Sees images** (\`--image path.png\`, repeatable): \`${VISION_SEATS.join('`, `')}\``,
    `- **Blind** — dropped from any convene with an image attached and NAMED on stdout, never silently: \`${blind.join('`, `')}\``,
    `- **Live web + X** (\`--research\`): \`${SEARCH_SEATS.join('`, `')}\``,
    `- **Trains on input** — dropped by \`--private\`, and \`--trading\` implies \`--private\`: \`${TRAINS_ON_INPUT_SEATS.join('`, `')}\``,
    '',
    'Run `node scripts/council/council.js` with no arguments for the live roster, and',
    '`node scripts/council/health.js` to check every seat is actually answering.',
    '',
    END,
  ].join('\n');
}

function apply(file, block) {
  if (!fs.existsSync(file)) return { file, status: 'absent' };
  const src = fs.readFileSync(file, 'utf8');
  const i = src.indexOf(BEGIN);
  const j = src.indexOf(END);
  if (i === -1 || j === -1) return { file, status: 'no-markers' };
  const next = src.slice(0, i) + block + src.slice(j + END.length);
  if (next === src) return { file, status: 'current' };
  return { file, status: 'stale', next };
}

function main() {
  const check = process.argv.includes('--check');
  const block = buildBlock();
  let stale = 0;
  let written = 0;
  for (const file of TARGETS) {
    const res = apply(file, block);
    if (res.status === 'absent') continue;
    if (res.status === 'no-markers') {
      console.error(`[sync-skill-doc] ${file}: generated-roster markers missing — add them or the doc cannot be kept in sync`);
      stale += 1;
      continue;
    }
    if (res.status === 'current') {
      if (!check) console.log(`[sync-skill-doc] ${file}: already current`);
      continue;
    }
    stale += 1;
    if (!check) {
      fs.writeFileSync(file, res.next);
      written += 1;
      console.log(`[sync-skill-doc] ${file}: UPDATED from roster.js`);
    } else {
      console.error(`[sync-skill-doc] ${file}: STALE — run \`node scripts/council/sync-skill-doc.js\``);
    }
  }
  // Mirror step runs AFTER the marker rewrite so Codex receives the regenerated doc.
  for (const m of MIRRORS) {
    const res = mirrorStatus(m.from, m.to);
    if (res.status === 'absent') continue;
    if (res.status === 'current') {
      if (!check) console.log(`[sync-skill-doc] ${m.to}: mirror already current`);
      continue;
    }
    stale += 1;
    if (!check) {
      fs.mkdirSync(path.dirname(m.to), { recursive: true });
      fs.writeFileSync(m.to, res.next);
      written += 1;
      console.log(`[sync-skill-doc] ${m.to}: MIRRORED from ${m.from}`);
    } else {
      console.error(`[sync-skill-doc] ${m.to}: STALE MIRROR — run \`node scripts/council/sync-skill-doc.js\``);
    }
  }
  if (check && stale) process.exit(1);
  if (!check) console.log(`[sync-skill-doc] done — ${written} file(s) written`);
}

if (require.main === module) main();

module.exports = { buildBlock, apply, mirrorStatus, BEGIN, END, TARGETS, MIRRORS };
