/** Pure: returns the next file content, or status for a file that is already current. */
function apply(src, block) {
  const i = src.indexOf(BEGIN);
  const j = src.indexOf(END);
  if (i !== -1 && j !== -1) {
    const next = src.slice(0, i) + block + src.slice(j + END.length);
    return next === src ? { status: 'current' } : { status: 'stale', next };
  }
  if (i !== -1 || j !== -1) return { status: 'broken-markers' };
  const k = src.indexOf(ANCHOR);
  const next = k !== -1
    ? src.slice(0, k + ANCHOR.length) + '\n\n' + block + '\n' + src.slice(k + ANCHOR.length)
    : block + '\n\n' + src;
  return { status: 'missing', next };
}

function main() {
  const check = process.argv.includes('--check');
  if (!fs.existsSync(TARGET)) {
    console.log(`[sync-codex-agents] ${TARGET} absent — Codex not installed here, nothing to do`);
    return;
  }
  const src = fs.readFileSync(TARGET, 'utf8');
  const res = apply(src, buildBlock());
  if (res.status === 'current') { console.log(`[sync-codex-agents] ${TARGET}: already current`); return; }
  if (res.status === 'broken-markers') {
    console.error(`[sync-codex-agents] ${TARGET}: one marker present without the other — repair by hand`);
    process.exit(1);
  }
  if (check) {
    console.error(`[sync-codex-agents] ${TARGET}: ${res.status.toUpperCase()} — run \`node scripts/codex/sync-codex-agents.js\``);
    process.exit(1);
  }
  fs.copyFileSync(TARGET, `${TARGET}.bak-${new Date().toISOString().slice(0, 10)}`);
  fs.writeFileSync(TARGET, res.next);
  console.log(`[sync-codex-agents] ${TARGET}: block ${res.status === 'missing' ? 'INSERTED' : 'UPDATED'} (${buildBlock().length} bytes)`);
}

if (require.main === module) main();
module.exports = { buildBlock, apply, BEGIN, END, ANCHOR, TARGET };
