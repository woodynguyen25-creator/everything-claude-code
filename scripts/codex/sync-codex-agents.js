/**
 * Write the AIOS capability block into ~/.codex/AGENTS.md — the ONE file Codex loads
 * on every turn — so Sol can summon the council and reach the trading toolkit the
 * same way Claude does, without depending on skill discovery.
 *
 * WHY NOT JUST THE SKILL
 * Codex caps skill metadata at 2% of context and silently drops the rest ("Exceeded
 * skills context budget", reference_gpt56_sol.md). With ~1,900 skills installed, a
 * skill Sol has not been told about by name may never surface. AGENTS.md is
 * always-loaded, so the invocation lives here; `$council` carries the long doctrine.
 *
 * WHY GENERATED
 * The roster line is built from roster.js. A hand-written seat list in this file
 * would be the fourth copy of a volatile fact to rot (see sync-skill-doc.js). OMX
 * regenerates AGENTS.md wholesale on `omx setup`; re-running this script re-inserts
 * the block. `--check` fails when the installed block is stale.
 *
 * Usage:
 *   node scripts/codex/sync-codex-agents.js          # write/refresh the block
 *   node scripts/codex/sync-codex-agents.js --check  # exit 1 if stale or missing
 */
'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

